'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),os=require('node:os');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'philips-standby-'));
process.env.PHILIPS_TV_CONFIG=path.join(dir,'credentials.json');
process.env.SHIELD_STATUS_DIR=dir;
const host='192.168.178.189';
fs.writeFileSync(process.env.PHILIPS_TV_CONFIG,JSON.stringify({host,user:'test',password:'fixture'}));
const driver=require('../docs/integrations/shield/philips-tv.js');
const {rememberLivingStatus}=require('../docs/integrations/shield/poll.js');
const now=Date.now();
let reads=0,healthCalls=0;
const read=powerstate=>async()=>{reads++;return {powerstate};};
const health=async()=>{healthCalls++;return true;};
const shield=(power='standby',online=true,updated=now)=>assert.equal(rememberLivingStatus({power,online},dir,updated),true);
(async()=>{
 shield('awake');
 await driver.collect(read('Standby'),health,()=>now);assert.equal(reads,1);
 shield();
 const paused=await driver.collect(read('On'),health,()=>now);
 assert.equal(reads,1);assert.equal(healthCalls,0,'Both-off guard must open no connection to TV');
 assert.equal(paused.power,'standby');assert.match(paused.error,/Ruhemodus/);
 delete require.cache[require.resolve('../docs/integrations/shield/philips-tv.js')];
 const restarted=require('../docs/integrations/shield/philips-tv.js');
 await restarted.collect(read('On'),health,()=>now);assert.equal(reads,1,'Guard must survive new poller process');
 shield('awake');
 assert.equal((await driver.collect(read('On'),health,()=>now)).power,'awake');assert.equal(reads,2);
 shield();await driver.collect(read('On'),health,()=>now);assert.equal(reads,3,'Shield standby alone must not pause an awake TV');
 shield('standby',false);await driver.collect(read('Standby'),health,()=>now);assert.equal(reads,4);
 shield('standby',false);await driver.collect(read('Standby'),health,()=>now);assert.equal(reads,5,'Offline Shield is not confirmed standby');
 shield('standby',true,now-151000);await driver.collect(read('Standby'),health,()=>now);assert.equal(reads,6,'Stale Shield must not hold guard closed');
 shield('standby',true,now+1000);await driver.collect(read('Standby'),health,()=>now);assert.equal(reads,7,'Future timestamps must not hold guard closed');
 shield();
 const command={id:'a'.repeat(24),action:'sleep',expires:Math.floor(Date.now()/1000)+40};
 let writes=0;
 assert.equal(await driver.execute(command,async()=>writes++),true);assert.equal(writes,0,'Already-off command must not connect');
 await driver.execute({...command,action:'wake'},async(method,uri,body)=>{assert.deepEqual(body,{powerstate:'On'});writes++;});
 assert.equal(writes,1,'Wake must bypass guard');
 assert.equal(driver.bothStandby(),false,'Wake must cancel cached standby');
 await driver.collect(read('On'),health,()=>Date.now());assert.equal(reads,8);
 shield('awake');await driver.collect(read('Standby'),health,()=>Date.now());
 await driver.execute(command,async()=>writes++); // Shield awake: issue explicit OFF, then remember successful acknowledgement.
 shield('standby',true,Date.now());
 assert.equal(driver.bothStandby(),true);
 shield('awake',true,Date.now());
 await driver.collect(async()=>{throw Error('ECONNRESET');},health);
 shield('standby',true,Date.now());assert.equal(driver.bothStandby(),false,'Connection errors must invalidate a previous standby observation');
 fs.writeFileSync(path.join(dir,'wohnzimmer-status.json'),'bad');assert.equal(driver.bothStandby(),false);
 console.log('TV standby guard: no network, restart persistence, wake, redundant off and stale/error recovery passed');
})().catch(e=>{console.error(e);process.exitCode=1;});
