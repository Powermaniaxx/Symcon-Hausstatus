'use strict';
const assert=require('node:assert/strict'),crypto=require('node:crypto'),fs=require('node:fs'),path=require('node:path'),os=require('node:os');
const directory=fs.mkdtempSync(path.join(os.tmpdir(),'philips-tv-fixture-'));
process.env.PHILIPS_TV_CONFIG=path.join(directory,'credentials.json');
const config={host:'192.168.178.190',user:'fixture',password:'not-a-real-password',mac:'02:11:22:33:44:55',broadcast:'192.168.178.255'};
fs.writeFileSync(process.env.PHILIPS_TV_CONFIG,JSON.stringify(config));
const {digest,api,wakePacket,execute,applyPendingHdmi3,collect}=require('../docs/integrations/shield/philips-tv.js');
const challenge='Digest realm="XTV", nonce="fixture-nonce", algorithm=MD5, qop="auth"';
const md5=s=>crypto.createHash('md5').update(s).digest('hex');
const header=digest(challenge,'POST','/6/powerstate',config);
const cnonce=header.match(/cnonce="([^"]+)"/)[1];
assert.ok(header.includes(md5([md5(config.user+':XTV:'+config.password),'fixture-nonce','00000001',cnonce,'auth',md5('POST:/6/powerstate')].join(':'))));
const packet=wakePacket(config.mac);assert.equal(packet.length,102);assert.equal(packet.subarray(0,6).toString('hex'),'ffffffffffff');
assert.equal(packet.subarray(6,12).toString('hex'),'021122334455');
assert.throws(()=>wakePacket('bad'),/MAC/);
(async()=>{
 let requests=0;
 const result=await api('GET','powerstate',undefined,config,async(method,uri,body,auth)=>{
  requests++;assert.equal(uri,'/6/powerstate');
  return auth?{status:200,text:'{"powerstate":"On"}'}:{status:401,challenge,text:''};
 });
 assert.equal(requests,2);assert.equal(result.powerstate,'On');
 let retryCount=0;
 const tlsError=new Error('Client network socket disconnected before secure TLS connection was established');
 const partial=await collect(async()=>{throw tlsError;},async()=>true);
 assert.equal(partial.online,true);assert.equal(partial.power,'unknown');assert.match(partial.error,/verschlüsselte Steuerung/);
 const offline=await collect(async()=>{throw tlsError;},async()=>false);
 assert.equal(offline.online,false);assert.equal(offline.power,'unknown');
 const unpaired=await collect(async()=>{throw Error('Philips TV muss per PIN gekoppelt werden.');},async()=>{throw Error('Must not probe on auth errors');});
 assert.equal(unpaired.online,false);assert.match(unpaired.error,/PIN/);
 const recovered=await api('GET','powerstate',undefined,config,async()=>{
  if(++retryCount===1)throw tlsError;
  return {status:200,text:'{"powerstate":"On"}'};
 });
 assert.equal(recovered.powerstate,'On');assert.equal(retryCount,2);
 let failedReads=0;
 await assert.rejects(api('GET','powerstate',undefined,config,async()=>{failedReads++;throw tlsError;}));
 assert.equal(failedReads,2);
 let failedWrites=0;
 await assert.rejects(api('POST','powerstate',{powerstate:'Standby'},config,async()=>{failedWrites++;throw tlsError;}));
 assert.equal(failedWrites,1);
 let pinReads=0;
 await assert.rejects(api('GET','powerstate',undefined,config,async()=>{pinReads++;return {status:401,challenge,text:''};}),/gekoppelt/);
 assert.equal(pinReads,2); // challenge + authentication, no retry on rejected credentials.
 await assert.rejects(api('GET','powerstate',undefined,config,async()=>({status:401,challenge,text:''})),/gekoppelt/);
 const command={id:'a'.repeat(24),action:'wake',expires:Math.floor(Date.now()/1000)+40};
 let bodies=[];await execute(command,async(method,uri,body)=>bodies.push(body));
 assert.deepEqual(bodies,[{powerstate:'On'}]);
 let sources=[];
 const pendingFile=process.env.PHILIPS_TV_CONFIG+'.hdmi3-pending';
 assert.equal(fs.existsSync(pendingFile),false,'Wake must not schedule HDMI switching');
 fs.writeFileSync(pendingFile,JSON.stringify({until:Date.now()+90000}));
 await applyPendingHdmi3(config,false,async(method,uri,body)=>sources.push(body));
 assert.equal(sources.length,0);
 await applyPendingHdmi3(config,true,async(method,uri,body)=>{assert.equal(uri,'activities/launch');sources.push(body);});
 assert.deepEqual(sources,[]);
 assert.equal(fs.existsSync(pendingFile),false,'Legacy HDMI request must be cancelled');
 await applyPendingHdmi3(config,true,async()=>sources.push('duplicate'));
 assert.equal(sources.length,0);
 await execute({...command,action:'hdmi3'},async(method,uri,body)=>sources.push(body));
 assert.deepEqual(sources,[],'Old queued HDMI commands must not reach the TV');
 await execute({...command,action:'sleep'},async(method,uri,body)=>bodies.push(body));
 assert.deepEqual(bodies[1],{powerstate:'Standby'});
 await applyPendingHdmi3(config,true,async()=>{throw new Error('Standby must cancel pending source');});
 let wakeCount=0;
 await execute(command,async()=>{throw new Error('Philips TV nicht erreichbar (Timeout).');},async mac=>{assert.equal(mac,config.mac);wakeCount++;});
 assert.equal(wakeCount,1);
 await execute(command,async()=>{throw tlsError;},async()=>wakeCount++);
 assert.equal(wakeCount,2);
 await assert.rejects(execute(command,async()=>{throw new Error('Philips TV muss per PIN gekoppelt werden.');},async()=>wakeCount++),/PIN/);
 assert.equal(wakeCount,2);
 assert.equal(await execute({...command,expires:1}),false);
 await assert.rejects(execute({...command,action:'toggle'}),/Ungültiger/);
 const backoffFile=process.env.PHILIPS_TV_CONFIG+'.connection-backoff.json';
 if(fs.existsSync(backoffFile))fs.unlinkSync(backoffFile);
 let clock=Date.now(),reads=0;
 const fail=async()=>{reads++;throw tlsError;};
 for(let i=0;i<3;i++)await collect(fail,async()=>true,()=>clock);
 assert.equal(reads,3);
 let saved=JSON.parse(fs.readFileSync(backoffFile,'utf8'));
 assert.equal(saved.nextAttempt-clock,120000);
 const paused=await collect(fail,async()=>true,()=>clock);
 assert.equal(reads,3,'Paused status must not open another HTTPS connection');
 assert.equal(paused.online,true);assert.equal(paused.power,'unknown');assert.match(paused.error,/pausiert/);
 assert.equal((await collect(fail,async()=>false,()=>clock)).online,false,'Public reachability must remain current while HTTPS is paused');
 clock=saved.nextAttempt;
 await collect(fail,async()=>true,()=>clock);
 assert.equal(reads,4);
 saved=JSON.parse(fs.readFileSync(backoffFile,'utf8'));assert.equal(saved.nextAttempt-clock,240000);
 clock=saved.nextAttempt;await collect(fail,async()=>true,()=>clock);
 saved=JSON.parse(fs.readFileSync(backoffFile,'utf8'));assert.equal(saved.nextAttempt-clock,300000);
 clock=saved.nextAttempt;
 const healthy=await collect(async()=>({powerstate:'On'}),async()=>true,()=>clock);
 assert.equal(healthy.power,'awake');assert.equal(fs.existsSync(backoffFile),false,'Successful status must reset persisted failures');
 fs.writeFileSync(backoffFile,JSON.stringify({failures:5,nextAttempt:Date.now()+300000}));
 let manual=0;
 await execute({...command,expires:Math.floor(Date.now()/1000)+40},async(method,uri,body)=>{manual++;assert.deepEqual(body,{powerstate:'On'});});
 assert.equal(manual,1,'Power commands must bypass the status pause');
 assert.equal(fs.existsSync(backoffFile),false,'Power command must allow a fresh status probe');
 fs.writeFileSync(backoffFile,'broken');
 assert.equal((await collect(async()=>({powerstate:'Standby'}),async()=>true)).power,'standby','Malformed cache must not block recovery');
 console.log('Philips status backoff, recovery, explicit power, digest and WLAN wake: passed');
})().catch(error=>{console.error(error);process.exitCode=1;});
