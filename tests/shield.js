'use strict';
const assert = require('node:assert/strict');
const {parse} = require('../docs/integrations/shield/poll.js');
const power = 'mWakefulness=Awake';
const activity = 'mResumedActivity: ActivityRecord{123 u0 org.smarttube.stable/Main t1}';
const session = (pkg,active,state,title,updated=12) => `\n package=${pkg}\n active=${active}\n state=PlaybackState {state=${state}, updated=${updated}}\n metadata: size=6, description=${title}, Author • views, null\n`;
const smart = session('org.smarttube.stable',true,3,'Titel, mit Komma');
const inactive = session('com.soundcloud.android',false,3,'Alter Titel');
assert.equal(parse(power,activity,smart+inactive).title,'Titel, mit Komma');
assert.equal(parse(power,activity,smart+inactive).playback,'playing');
assert.equal(parse(power,activity,smart.replace('state=3','state=2')).playback,'paused');
assert.equal(parse('mWakefulness=Asleep',activity,smart).title,'');
assert.equal(parse('mWakefulness=Dozing',activity,smart).power,'standby');
assert.equal(parse('',activity,smart).power,'unknown');
assert.equal(parse(power,activity,inactive).title,'');
assert.equal(parse(power,activity,inactive).playback,'stopped');
assert.equal(parse(power,activity,session('old.app',true,2,'Stale paused')).title,'');
assert.equal(parse(power,activity,session('music.app',true,3,'Background audio')).title,'Background audio');
assert.equal(parse(power,activity,smart+session('music.app',true,3,'Other',99)).title,'Titel, mit Komma');
assert.equal(parse(power,activity,session('org.smarttube.stable',true,6,'Buffering')).playback,'unknown');
console.log('Shield parser: 12 checks passed');
